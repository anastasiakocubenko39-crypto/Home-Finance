function findRecipe(text) {
  const t = norm(text);
  let best = null, len = 0;
  for (const r of RECIPES) for (const a of r.aliases) if (t.includes(norm(a)) && a.length > len) { best = r; len = a.length; }
  return best;
}
function parsePortions(text) {
  const t = norm(text);
  let m = t.match(new RegExp(`(?:на\\s+)?${NUM}\\s*(?:порці\\S*|персон\\S*|людин\\S*|осіб|особ\\S*|чолов\\S*)`));
  if (m) return Math.max(1, Math.round(toNum(m[1])));
  m = t.match(/на\s+(двох|трьох|чотирьох|п'ятьох|шістьох|\d+)/);
  if (m) return toNum(m[1]) || +m[1];
  return null;
}

/* ── таблиця БЖУ ── */
const r1 = (x) => (Math.round(x * 10) / 10).toLocaleString('uk-UA');
const r0 = (x) => Math.round(x).toLocaleString('uk-UA').replace(/,/g, ' ');
function table(items, portions) {
  let T = { p: 0, f: 0, c: 0, kcal: 0, g: 0 };
  const rows = items.map((it) => {
    const n = it.key ? nutritionOf(it.key, it.grams) : null;
    if (n) { T.p += n.p; T.f += n.f; T.c += n.c; T.kcal += n.kcal; T.g += it.grams; }
    return { it, n };
  });
  const missing = rows.filter((r) => !r.n);
  const per = (x) => x / portions;
  return {
    totals: T, portions, missing: missing.map((r) => r.it.raw || r.it.name),
    html: `<table class="nt"><thead><tr><th>Інгредієнт</th><th>г</th><th>ккал</th><th>Б</th><th>Ж</th><th>В</th></tr></thead><tbody>
      ${rows.map(({ it, n }) => `<tr${n ? '' : ' class="miss"'}><td>${esc(it.name)}</td><td>${it.grams != null ? r0(it.grams) : '—'}</td><td>${n ? r0(n.kcal) : '?'}</td><td>${n ? r1(n.p) : ''}</td><td>${n ? r1(n.f) : ''}</td><td>${n ? r1(n.c) : ''}</td></tr>`).join('')}
      </tbody><tfoot><tr><td>Усього</td><td>${r0(T.g)}</td><td>${r0(T.kcal)}</td><td>${r1(T.p)}</td><td>${r1(T.f)}</td><td>${r1(T.c)}</td></tr>
      ${portions > 1 ? `<tr class="pp"><td>1 порція (з ${portions})</td><td>${r0(per(T.g))}</td><td>${r0(per(T.kcal))}</td><td>${r1(per(T.p))}</td><td>${r1(per(T.f))}</td><td>${r1(per(T.c))}</td></tr>` : ''}</tfoot></table>`,
  };
}
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const fmtQty = (g, key) => {
  const pc = PIECE[key];
  if (pc && pc >= 20 && Math.abs(g / pc - Math.round(g / pc)) < 0.25 && Math.round(g / pc) >= 1) return `${Math.round(g / pc)} шт (≈${r0(g)} г)`;
  return g >= 1000 ? `${r1(g / 1000)} кг` : `${r0(g)} г`;
};

