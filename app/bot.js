export function findFood(name) {
  const n = norm(name).replace(/^(свіж\S*|варен\S*|смажен\S*|дрібн\S*|велик\S*|середн\S*|маленьк\S*)\s+/, '');
  if (!n) return null;
  if (NUTRITION[n]) return n;
  if (ALIAS[n]) return ALIAS[n];
  for (const [a, k] of Object.entries(ALIAS)) if (n.includes(a) && a.length > 4) return k;
  const words = n.split(' ').filter((w) => w.length > 1);
  let best = null, score = 0;
  for (const k of KEYS) {
    const kw = k.split(' ');
    const hit = kw.filter((w) => words.some((x) => stem(x) === stem(w) || x.startsWith(stem(w)) || w.startsWith(stem(x)))).length;
    const s = hit / kw.length + (hit === kw.length ? 1 : 0) - (kw.length - hit) * 0.3;
    if (hit && s > score) { score = s; best = k; }
  }
  return score >= 1 ? best : null;
}

/* ── розбір одного інгредієнта: «картопля 500 г», «2 яйця», «1,5 кг курки», «ст.л. олії» ── */
const UNIT_RE = '(кг|кілограм\\S*|г|гр|грам\\S*|мл|л|літр\\S*|шт|штук\\S*|ст\\.?\\s?л\\.?|столов\\S* ложк\\S*|ч\\.?\\s?л\\.?|чайн\\S* ложк\\S*|склянк\\S*|чашк\\S*|щіпк\\S*|зубч\\S*|пучк?\\S*|жмен\\S*|пачк\\S*|банк\\S*)';
function unitKey(u) {
  u = (u || '').toLowerCase().replace(/\s/g, '');
  if (/^кг|^кілограм/.test(u)) return 'кг';
  if (/^мл/.test(u)) return 'мл';
  if (/^л$|^літр/.test(u)) return 'л';
  if (/^г|^гр/.test(u)) return 'г';
  if (/^шт/.test(u)) return 'шт';
  if (/^ст\.?л|^столов/.test(u)) return 'ст.л';
  if (/^ч\.?л|^чайн/.test(u)) return 'ч.л';
  if (/^склян/.test(u)) return 'склянка';
  if (/^чашк/.test(u)) return 'чашка';
  if (/^щіп/.test(u)) return 'щіпка';
  if (/^зубч/.test(u)) return 'зубчик';
  if (/^пуч/.test(u)) return 'пучок';
  if (/^жмен/.test(u)) return 'жменя';
  if (/^пачк/.test(u)) return 'пачка';
  if (/^банк/.test(u)) return 'банка';
  return '';
}
const toNum = (s) => (s == null ? null : WORDNUM[s] ?? parseFloat(String(s).replace(',', '.')));
const NUM = "(\\d+(?:[.,]\\d+)?|пів|півтора|один|одна|одну|два|дві|три|чотири|п'ять|пять|шість|сім|вісім|десять)";
export function parseItem(seg) {
  let s = norm(seg).replace(/^[-–—•*\d]+[.)]\s+/, '').replace(/\s[-–—:]\s?/g, ' ');
  if (!s) return null;
  let m, qty = null, unit = '', name = s;
  if ((m = s.match(new RegExp(`^${NUM}\\s*${UNIT_RE}?\\s+(.+)$`)))) { qty = toNum(m[1]); unit = unitKey(m[2]); name = m[3]; }
  else if ((m = s.match(new RegExp(`^(.+?)\\s+${NUM}\\s*${UNIT_RE}?$`)))) { name = m[1]; qty = toNum(m[2]); unit = unitKey(m[3]); }
  else if ((m = s.match(new RegExp(`^${UNIT_RE}\\s+(.+)$`)))) { qty = 1; unit = unitKey(m[1]); name = m[2]; }
  name = name.replace(/^(?:кг|г|гр|мл|шт)\s+/, '').trim();
  const key = findFood(name);
  let grams = null;
  if (qty != null) {
    if (unit === 'кг' || unit === 'л') grams = qty * 1000;
    else if (unit === 'г' || unit === 'мл') grams = qty;
    else if (unit === 'шт' || !unit) grams = qty * (PIECE[key] || PIECE[name] || (key && /олія|сіль|цукор|перець чорний/.test(key) ? 5 : 100));
    else grams = qty * (SPOON[unit] || 15) * (unit.includes('.л') ? (SPOON_DENSITY[key] || 1) : 1);
    if (unit === 'зубчик') grams = qty * 5;
  }
  return { raw: seg.trim(), name: key || name, key, qty, unit, grams };
}
export function nutritionOf(key, grams) {
  const n = NUTRITION[key]; if (!n || grams == null) return null;
  const k = grams / 100;
  const p = n.p * k, f = n.f * k, c = n.c * k;
  return { p, f, c, kcal: p * 4 + f * 9 + c * 4 };
}

