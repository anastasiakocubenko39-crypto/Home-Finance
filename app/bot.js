export function financeTips(ctx) {
  const out = [];
  const { budget, spent, byCat, prevSpent, prevByCat, daysLeft, catNames } = ctx;
  if (ctx.next) out.push(`До наступного надходження (${ctx.next.name.toLowerCase()}, ${ctx.next.label}) — <b>${ctx.next.days} дн.</b> ${ctx.pay?.per > 0 ? ` Щоб протриматись, витрачайте до <b>${r0(ctx.pay.per)} грн на день</b>.` : ctx.pay && ctx.pay.avail <= 0 ? ' Гроші до цього дня вже витрачено — відкладіть необов’язкові покупки.' : ''}`);
  if (budget > 0) {
    const left = budget - spent;
    if (left < 0) out.push(`Бюджет місяця перевищено на <b>${r0(-left)} грн</b>. Спробуйте до кінця місяця обмежитись найнеобхіднішим і перенести великі покупки.`);
    else if (daysLeft > 0 && !ctx.next) out.push(`До кінця місяця ${daysLeft} дн. Щоб вкластися в бюджет, можна витрачати до <b>${r0(left / daysLeft)} грн на день</b>.`);
    if (spent / budget > 0.8 && left >= 0) out.push(`Використано ${Math.round(spent / budget * 100)}% бюджету — час пригальмувати з необов’язковими витратами.`);
  } else out.push('Задайте бюджет на місяць на вкладці «Огляд» — тоді я рахуватиму денний ліміт і попереджатиму про перевищення.');
  const cats = Object.entries(byCat).filter(([, v]) => v > 0).sort((a, b) => b[1] - a[1]);
  if (cats.length && spent > 0) {
    const [c, v] = cats[0];
    out.push(`Найбільше йде на «${catNames[c] || c}»: <b>${r0(v)} грн</b> (${Math.round(v / spent * 100)}% усіх витрат).`);
  }
  for (const [c, v] of cats) {
    const pv = prevByCat[c] || 0;
    if (pv > 0 && v > pv * 1.2 && v - pv > 300) out.push(`«${catNames[c] || c}» цього місяця вже на <b>${r0(v - pv)} грн</b> більше, ніж за весь минулий місяць.`);
  }
  if (prevSpent > 0 && spent < prevSpent * 0.85) out.push(`Гарний результат: поки що витрачено на ${r0(prevSpent - spent)} грн менше, ніж минулого місяця.`);
  if ((byCat.walks || 0) > (byCat.products || 0) && (byCat.walks || 0) > 0) out.push('Прогулянки й кафе обходяться дорожче за продукти — спробуйте пікнік або вечір вдома з друзями замість одного виходу.');
  const shuffled = [...GENERAL_TIPS].sort(() => Math.random() - 0.5).slice(0, 3);
  return [...out, ...shuffled];
}

/* ── головна функція бота ── */
export function reply(text, ctx = {}) {
  const t = norm(text);
  if (!t) return { html: 'Напишіть, що готуєте — наприклад: <i>«роблю том ям на 4 порції»</i> або <i>«суп: картопля 500 г, курка 400 г, морква 1 шт, цибуля 1 шт»</i>.' };
  if (/^(привіт|вітаю|добр|хай|hello|hi)\b/.test(t) || /що (ти )?вмієш|допомож/.test(t)) return { html: HELP };
  if (/еконо|заощад|зекон|порад|совет|витрат|витрача|бюджет|грош|мінус|скорот|урізат|дорого|переплач|не вистача|куди йдуть|на що йдуть|борг|зарплат|накопич|відклас/.test(t)) {
    const tips = financeTips(ctx.finance || { budget: 0, spent: 0, byCat: {}, prevSpent: 0, prevByCat: {}, daysLeft: 0, catNames: {} });
    return { html: `<b>Поради для вашого бюджету</b><ul>${tips.map((x) => `<li>${x}</li>`).join('')}</ul>` };
  }
  const portions = parsePortions(text);
  const intent = /рецепт|роблю|готую|зварю|варю|приготу|хочу|як зробити|як приготувати/.test(t);
  // прибираємо «на 4 порції» з тексту, щоб не заважало розбору інгредієнтів
  const clean = text.replace(new RegExp(`[-–—,]?\\s*(?:на\\s+)?${NUM}\\s*(?:порці\\S*|персон\\S*|людин\\S*|осіб|особ\\S*)`, 'i'), '').replace(/[-–—,]?\s*на\s+(двох|трьох|чотирьох|п'ятьох|шістьох)/i, '');
  const colon = clean.indexOf(':');
  const head = colon > -1 ? clean.slice(0, colon).trim() : '';
  const body = colon > -1 ? clean.slice(colon + 1) : clean;
  const segs = body.split(/[\n;,]+|\s+(?:і|та|й|ще|плюс)\s+(?=\d)/).map((x) => x.trim()).filter(Boolean);
  const items = segs.map(parseItem).filter((x) => x && x.grams != null);
  const known = items.filter((x) => x.key);
  const recipe = findRecipe(head || (known.length ? '' : clean)) || (!known.length || intent && known.length < 2 ? findRecipe(clean) : null);
  if (known.length >= 2 || (known.length === 1 && !(recipe && intent))) {
    const P = portions || 1;
    if (known.length === 1 && items.length === 1 && P === 1) {
      const it = known[0]; const n = nutritionOf(it.key, it.grams);
      return { html: `<b>${esc(it.key)}, ${r0(it.grams)} г</b>: ${r0(n.kcal)} ккал · білки ${r1(n.p)} г · жири ${r1(n.f)} г · вуглеводи ${r1(n.c)} г` };
    }
    const tb = table(items, P);
    const title = head ? head.replace(/^(я\s+)?(роблю|готую|варю)\s+/i, '') : 'Ваша страва';
    return {
      html: `<b>${esc(title.charAt(0).toUpperCase() + title.slice(1))}${P > 1 ? ` — ${P} порц.` : ''}</b>${tb.html}
        ${tb.missing.length ? `<p class="muted">Не знайшла у словнику: ${tb.missing.map(esc).join(', ')}. Напишіть інакше (наприклад «куряче філе 300 г») або вкажіть вагу.</p>` : ''}
        ${P === 1 ? '<p class="muted">Напишіть «на 4 порції», і я поділю БЖУ на порції.</p>' : ''}`,
      dish: { title, portions: P, totals: tb.totals, items: known.map((x) => ({ name: x.key, grams: Math.round(x.grams) })) },
    };
  }
  if (recipe) {
    const P = portions || 2;
    const items = recipe.items.map(([k, g]) => ({ name: k, key: NUTRITION[k] ? k : findFood(k), grams: g * P, raw: k }));
    const tb = table(items, P);
    return {
      html: `<b>${esc(recipe.title)} на ${P} порц.</b>${portions ? '' : ' <span class="muted">(за замовчуванням; напишіть «на 4 порції», щоб перерахувати)</span>'}
        <div class="ing">${items.map((i) => `<span>${esc(i.name)} — ${fmtQty(i.grams, i.key)}</span>`).join('')}</div>
        <ol>${recipe.steps.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>${tb.html}`,
      dish: { title: recipe.title, portions: P, totals: tb.totals, items: items.map((x) => ({ name: x.name, grams: Math.round(x.grams) })) },
    };
  }
  const single = parseItem(text);
  if (single && single.key) {
    const g = single.grams ?? 100;
    const n = nutritionOf(single.key, g);
    return { html: `<b>${esc(single.key)}, ${r0(g)} г</b>: ${r0(n.kcal)} ккал · білки ${r1(n.p)} г · жири ${r1(n.f)} г · вуглеводи ${r1(n.c)} г` };
  }
  return { html: `Не зовсім зрозуміла. ${HELP}` };
}
